alter table public.workspace_members enable row level security;
alter table public.projects enable row level security;
alter table public.issues enable row level security;
alter table public.issue_comments enable row level security;
alter table public.labels enable row level security;
alter table public.issue_labels enable row level security;

create policy "Users can read their own profile" on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy "Users can create their own profile" on public.profiles for insert to authenticated with check (id = (select auth.uid()));
create policy "Users can update their own profile" on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy "Members can read workspaces" on public.workspaces for select to authenticated using (public.is_workspace_member(id) or created_by = (select auth.uid()));
create policy "Authenticated users can create workspaces" on public.workspaces for insert to authenticated with check (created_by = (select auth.uid()));
create policy "Workspace admins can update workspaces" on public.workspaces for update to authenticated using (public.can_manage_workspace(id)) with check (public.can_manage_workspace(id));

create policy "Members can read workspace membership" on public.workspace_members for select to authenticated using (public.is_workspace_member(workspace_id) or user_id = (select auth.uid()));
create policy "Workspace admins can add members" on public.workspace_members for insert to authenticated with check (public.can_manage_workspace(workspace_id) or (user_id = (select auth.uid()) and exists (select 1 from public.workspaces w where w.id = workspace_id and w.created_by = (select auth.uid())));
create policy "Workspace admins can update members" on public.workspace_members for update to authenticated using (public.can_manage_workspace(workspace_id)) with check (public.can_manage_workspace(workspace_id));
create policy "Workspace admins can remove members" on public.workspace_members for delete to authenticated using (public.can_manage_workspace(workspace_id));

create policy "Workspace members can read projects" on public.projects for select to authenticated using (public.is_workspace_member(workspace_id));
create policy "Workspace admins can create projects" on public.projects for insert to authenticated with check (public.can_manage_workspace(workspace_id) and created_by = (select auth.uid()));
create policy "Workspace admins can update projects" on public.projects for update to authenticated using (public.can_manage_workspace(workspace_id)) with check (public.can_manage_workspace(workspace_id));
create policy "Workspace admins can delete projects" on public.projects for delete to authenticated using (public.can_manage_workspace(workspace_id));

create policy "Project members can read issues" on public.issues for select to authenticated using (public.is_project_member(project_id));
create policy "Project members can create issues" on public.issues for insert to authenticated with check (public.is_project_member(project_id) and reporter_id = (select auth.uid()));
create policy "Project members can update issues" on public.issues for update to authenticated using (public.is_project_member(project_id)) with check (public.is_project_member(project_id));
create policy "Project admins can delete issues" on public.issues for delete to authenticated using (exists (select 1 from public.projects p where p.id = project_id and public.can_manage_workspace(p.workspace_id)));

create policy "Project members can read comments" on public.issue_comments for select to authenticated using (exists (select 1 from public.issues i where i.id = issue_id and public.is_project_member(i.project_id)));
create policy "Project members can add comments" on public.issue_comments for insert to authenticated with check (author_id = (select auth.uid()) and exists (select 1 from public.issues i where i.id = issue_id and public.is_project_member(i.project_id)));
create policy "Authors can update comments" on public.issue_comments for update to authenticated using (author_id = (select auth.uid())) with check (author_id = (select auth.uid()));
create policy "Authors or workspace admins can delete comments" on public.issue_comments for delete to authenticated using (author_id = (select auth.uid()) or exists (select 1 from public.issues i join public.projects p on p.id = i.project_id where i.id = issue_id and public.can_manage_workspace(p.workspace_id)));

create policy "Project members can read labels" on public.labels for select to authenticated using (public.is_project_member(project_id));
create policy "Project members can manage labels" on public.labels for all to authenticated using (public.is_project_member(project_id)) with check (public.is_project_member(project_id));
create policy "Project members can read issue labels" on public.issue_labels for select to authenticated using (exists (select 1 from public.issues i where i.id = issue_id and public.is_project_member(i.project_id)));
create policy "Project members can manage issue labels" on public.issue_labels for all to authenticated using (exists (select 1 from public.issues i where i.id = issue_id and public.is_project_member(i.project_id))) with check (exists (select 1 from public.issues i where i.id = issue_id and public.is_project_member(i.project_id)));

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.profiles, public.workspaces, public.workspace_members, public.projects, public.issues, public.issue_comments, public.labels, public.issue_labels to authenticated;
