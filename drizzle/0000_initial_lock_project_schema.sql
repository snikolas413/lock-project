create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 120),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member', 'viewer')),
  joined_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 160),
  key text not null check (key ~ '^[A-Z][A-Z0-9]{1,9}$'),
  description text,
  status text not null default 'active' check (status in ('active', 'archived')),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, key)
);

create table public.issues (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  issue_number bigint generated by default as identity,
  title text not null check (char_length(trim(title)) between 1 and 240),
  description text,
  type text not null default 'task' check (type in ('epic', 'story', 'task', 'bug', 'subtask')),
  status text not null default 'backlog' check (status in ('backlog', 'todo', 'in_progress', 'in_review', 'done', 'cancelled')),
  priority text not null default 'medium' check (priority in ('lowest', 'low', 'medium', 'high', 'highest')),
  reporter_id uuid not null references auth.users(id) on delete restrict,
  assignee_id uuid references auth.users(id) on delete set null,
  due_date date,
  position numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (project_id, issue_number)
);

create table public.issue_comments (
  id uuid primary key default gen_random_uuid(),
  issue_id uuid not null references public.issues(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete restrict,
  body text not null check (char_length(trim(body)) between 1 and 10000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.labels (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 50),
  color text not null default '#64748b' check (color ~ '^#[0-9A-Fa-f]{6}$'),
  created_at timestamptz not null default now(),
  unique (project_id, name)
);

create table public.issue_labels (
  issue_id uuid not null references public.issues(id) on delete cascade,
  label_id uuid not null references public.labels(id) on delete cascade,
  primary key (issue_id, label_id)
);

create index workspace_members_user_id_idx on public.workspace_members(user_id);
create index projects_workspace_id_idx on public.projects(workspace_id);
create index issues_project_status_idx on public.issues(project_id, status);
create index issues_assignee_id_idx on public.issues(assignee_id);
create index issue_comments_issue_id_idx on public.issue_comments(issue_id);
create index labels_project_id_idx on public.labels(project_id);

create or replace function public.is_workspace_member(target_workspace_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.workspace_members wm where wm.workspace_id = target_workspace_id and wm.user_id = (select auth.uid()));
$$;

create or replace function public.can_manage_workspace(target_workspace_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.workspace_members wm where wm.workspace_id = target_workspace_id and wm.user_id = (select auth.uid()) and wm.role in ('owner', 'admin'));
$$;

create or replace function public.is_project_member(target_project_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.projects p join public.workspace_members wm on wm.workspace_id = p.workspace_id where p.id = target_project_id and wm.user_id = (select auth.uid()));
$$;

